// Lightweight i18n for Carva GPS: English, Arabic, and Sorani Kurdish (both RTL).
// No external deps and no route restructuring — locale lives in a cookie, the
// server layout sets <html lang dir>, and a client provider switches at runtime.

export type Locale = 'en' | 'ar' | 'ckb';

export const DEFAULT_LOCALE: Locale = 'en';
export const LOCALE_COOKIE = 'carva-lang';

export const LOCALES: Record<Locale, { label: string; dir: 'ltr' | 'rtl' }> = {
  en: { label: 'English', dir: 'ltr' },
  ar: { label: 'العربية', dir: 'rtl' },
  ckb: { label: 'کوردیی ناوەندی', dir: 'rtl' },
};

export function isLocale(v: string | null | undefined): v is Locale {
  return v === 'en' || v === 'ar' || v === 'ckb';
}

export function dirFor(locale: Locale): 'ltr' | 'rtl' {
  return LOCALES[locale].dir;
}

